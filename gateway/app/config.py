"""Configuration for the inference gateway.

Deliberately free of any internal shared library. The gateway is small enough
that plain pydantic-settings is the lower-coupling choice over pulling in a
monorepo-wide settings package.
"""

from __future__ import annotations

from functools import lru_cache

from pydantic import Field
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(env_prefix="GATEWAY_", extra="ignore")

    # ── Upstream model server ────────────────────────────────────────────────
    # In-cluster address of the vLLM Service. Kept as a URL rather than
    # host/port so a local docker-compose run can point at anything.
    model_server_url: str = Field(default="http://model-server:8000")

    # Cold start after a scale-to-zero GPU node comes up is dominated by
    # loading multi-GB weights into VRAM. The read timeout has to survive that
    # or the first request after idle fails while the pod is healthy and simply
    # not ready yet.
    upstream_connect_timeout_s: float = 10.0
    upstream_read_timeout_s: float = 300.0

    # ── Caller authentication ────────────────────────────────────────────────
    # This gateway is private-by-default: it sits behind an internal load
    # balancer and the only legitimate callers are the services you name here.
    # The key authenticates *a calling service*, not an end user -- end-user
    # identity, tenancy and quota belong one layer up, in whatever fronts this
    # gateway publicly.
    gateway_api_key: str = Field(default="")

    # A second key for a second trusted caller (its own rotation and
    # revocation, apart from the first). Empty means that caller is not
    # accepted at all. This key is never the empty string, so an unset value
    # cannot match a blank header.
    gateway_secondary_api_key: str = Field(default="")

    # Fail closed or open when no key is configured. Defaults to closed: an
    # unauthenticated endpoint in front of a GPU is a direct route to someone
    # else's compute bill.
    require_auth: bool = True

    # ── Behaviour ────────────────────────────────────────────────────────────
    # Served model name advertised to callers. Keep this stable across model
    # swaps so the client contract survives replacing the base model with a
    # fine-tune.
    served_model_name: str = "default"

    # ── Routing (one gateway, routed by the request's `model` field) ────────
    # JSON file generated by scripts/generate_routes.py from whatever registry
    # of approved models you run. Empty means only the baked model, under
    # served_model_name, is routable. A missing or unreadable file is an
    # error, not an empty table, so a bad mount cannot silently send every
    # model to the baked one.
    routes_file: str = Field(default="")
    # Kubernetes namespace where each model's Service lives. Upstream is
    # http://<served name>.<namespace>.svc:8000.
    model_namespace: str = Field(default="inference")

    # ── Status and metering ─────────────────────────────────────────────────
    # Window the status view reports over. Counters are kept per replica and
    # reset when a pod restarts.
    status_window_hours: int = Field(default=24, ge=1, le=168)

    log_level: str = "INFO"


@lru_cache
def get_settings() -> Settings:
    return Settings()
